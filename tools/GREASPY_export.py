#!/usr/bin/env python3
"""Spectrum export helpers for GREASPY."""

from __future__ import annotations

import datetime as dt
import math
import struct
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Iterable, List, Optional, Sequence


DEFAULT_SHIELDING_MATERIALS = [
    "Polyethylene",
    "Aluminum",
    "Stainless Steel 316",
    "Tungsten",
    "Pb",
    "Depleted Uranium (DU)",
]

SUPPORTED_SPECTRUM_FORMATS = ("spe", "chn", "n42", "spc")
FORMAT_EXTENSIONS = {
    "spe": ".spe",
    "chn": ".chn",
    "n42": ".n42",
    "spc": ".spc",
}

DEFAULT_DETECTOR_DESCRIPTION = "GREASPY Random Generator IDM-200-V"
DEFAULT_ANALYSIS_PROGRAM = "Generated by GREASPY_random_spectrum.py"
DEFAULT_DETECTOR_NUMBER = 2
DEFAULT_SEGMENT_NUMBER = 1
INT32_MAX = 2_147_483_647
N42_NAMESPACE = "http://physics.nist.gov/N42/2011/N42"
XSI_NAMESPACE = "http://www.w3.org/2001/XMLSchema-instance"


def normalize_spectrum_format(format_name: Optional[str]) -> Optional[str]:
    if format_name is None:
        return None
    key = format_name.strip().lower().lstrip(".")
    if key == "xml":
        key = "n42"
    if key not in SUPPORTED_SPECTRUM_FORMATS:
        valid = ", ".join(SUPPORTED_SPECTRUM_FORMATS)
        raise ValueError(f"Unsupported spectrum format '{format_name}'. Valid formats: {valid}")
    return key


def infer_spectrum_format(path: Path, explicit_format: Optional[str] = None) -> str:
    explicit = normalize_spectrum_format(explicit_format)
    if explicit:
        return explicit

    suffix = path.suffix.lower().lstrip(".")
    if suffix == "xml":
        return "n42"
    if suffix in SUPPORTED_SPECTRUM_FORMATS:
        return suffix
    return "spe"


def extension_for_format(format_name: str) -> str:
    return FORMAT_EXTENSIONS[normalize_spectrum_format(format_name) or "spe"]


def ensure_format_extension(path: Path, format_name: str) -> Path:
    if path.suffix:
        return path
    return path.with_suffix(extension_for_format(format_name))


def write_spectrum_file(
    path: Path,
    inp: Any,
    res: Any,
    format_name: Optional[str] = None,
    detector_description: str = DEFAULT_DETECTOR_DESCRIPTION,
    analysis_program: str = DEFAULT_ANALYSIS_PROGRAM,
    measurement_datetime: Optional[dt.datetime] = None,
    shielding_materials: Sequence[str] = DEFAULT_SHIELDING_MATERIALS,
) -> str:
    """Write a GREASPY spectrum file and return the normalized format name."""

    out_path = Path(path)
    resolved_format = infer_spectrum_format(out_path, format_name)
    if resolved_format == "spe":
        out_path.write_text(
            "\n".join(
                build_spe_lines(
                    inp,
                    res,
                    detector_description=detector_description,
                    analysis_program=analysis_program,
                    measurement_datetime=measurement_datetime,
                    shielding_materials=shielding_materials,
                )
            )
            + "\n",
            encoding="utf-8",
        )
    elif resolved_format == "n42":
        out_path.write_text(
            build_n42_text(
                inp,
                res,
                detector_description=detector_description,
                analysis_program=analysis_program,
                measurement_datetime=measurement_datetime,
                shielding_materials=shielding_materials,
            ),
            encoding="utf-8",
        )
    elif resolved_format == "chn":
        out_path.write_bytes(
            build_chn_bytes(
                inp,
                res,
                detector_description=detector_description,
                sample_description=build_sample_description(inp),
                measurement_datetime=measurement_datetime,
                shielding_materials=shielding_materials,
            )
        )
    elif resolved_format == "spc":
        out_path.write_bytes(
            build_spc_bytes(
                inp,
                res,
                detector_description=detector_description,
                sample_description=build_sample_description(inp),
                spectrum_name=out_path.stem,
                measurement_datetime=measurement_datetime,
                shielding_materials=shielding_materials,
            )
        )
    else:
        raise AssertionError(f"Unhandled spectrum format: {resolved_format}")
    return resolved_format


def build_spe_lines(
    inp: Any,
    res: Any,
    detector_description: str = DEFAULT_DETECTOR_DESCRIPTION,
    analysis_program: str = DEFAULT_ANALYSIS_PROGRAM,
    measurement_datetime: Optional[dt.datetime] = None,
    shielding_materials: Sequence[str] = DEFAULT_SHIELDING_MATERIALS,
) -> List[str]:
    shield_on = _shielding_enabled(inp, shielding_materials)
    dose = _metric(res, shield_on, "shielded_dose_30cm", "unshielded_dose_30cm")
    dist20 = _metric(res, shield_on, "shielded_distance_20pct_cm", "unshielded_distance_20pct_cm")
    dead = _metric(res, shield_on, "shielded_dead_time_pct", "unshielded_dead_time_pct")
    emitted = _metric(res, shield_on, "shielded_gammas_emitted_s", "unshielded_gammas_emitted_s")
    incident = _metric(res, shield_on, "shielded_gammas_incident_s", "unshielded_gammas_incident_s")
    real_time = _real_time_seconds(inp, res, shielding_materials)

    measured_at = _local_datetime(measurement_datetime).strftime("%m/%d/%Y  %I:%M:%S %p")

    lines = [
        "$SPEC_ID:",
        f"Distance Measured = {inp.distance_cm:g} cm",
        f"Dose Rate (rem/hr) at 30 cm = {dose:.2E}",
        f"Distance (cm) Required for 20 Percent Dead Time = {dist20:.2E}",
        f"Dead Time (Percent) = {dead:.2E}",
        f"Total Gammas Emitted per Second by Source = {emitted:.2E}",
        f"Total Gammas Recorded per Second by Detector = {incident:.2E}",
    ]

    selected = list(inp.isotopes[:10])
    for i in range(10):
        if i < len(selected) and selected[i][0] and selected[i][1] > 0:
            name, act = selected[i]
            lines.append(f"Isotope {i + 1}: {name} = {act:.2E} Ci")
        else:
            lines.append(f"Isotope {i + 1}: None")

    lines.append(f"Background Included = {'YES' if inp.include_background else 'NO'}")
    for material in shielding_materials:
        lines.append(f"Shielding: {material} = {inp.shielding_cm.get(material, 0.0):g} cm")

    lines.extend(
        [
            "$SPEC_REM:",
            f"DET# {DEFAULT_DETECTOR_NUMBER}",
            f"DETDESC# {detector_description}",
            f"AP# {analysis_program}",
            "$DATE_MEA:",
            measured_at,
            "$MEAS_TIM:",
            f"{inp.count_time_sec:g} {real_time:.6f}",
            "$DATA:",
            f"0 {len(res.total_counts) - 1}",
        ]
    )

    for value in res.total_counts:
        lines.append(f"{float(value):.6f}")

    lines.extend(
        [
            "$ENER_FIT:",
            f"{float(res.eff_a):.6f} {float(res.eff_b):.6f}",
        ]
    )
    return lines


def build_chn_bytes(
    inp: Any,
    res: Any,
    detector_description: str = DEFAULT_DETECTOR_DESCRIPTION,
    sample_description: Optional[str] = None,
    measurement_datetime: Optional[dt.datetime] = None,
    detector_number: int = DEFAULT_DETECTOR_NUMBER,
    segment_number: int = DEFAULT_SEGMENT_NUMBER,
    shielding_materials: Sequence[str] = DEFAULT_SHIELDING_MATERIALS,
) -> bytes:
    counts = _integer_counts(res.total_counts, ".chn")
    channel_count = len(counts)
    _require_i16_range(channel_count, "CHN channel count")

    measured_at = _local_datetime(measurement_datetime)
    header = bytearray(32)
    struct.pack_into("<h", header, 0, -1)
    struct.pack_into("<h", header, 2, int(detector_number))
    struct.pack_into("<h", header, 4, int(segment_number))
    header[6:8] = _ascii_bytes(f"{measured_at.second:02d}", 2)
    struct.pack_into("<i", header, 8, _time_ticks_20ms(_real_time_seconds(inp, res, shielding_materials)))
    struct.pack_into("<i", header, 12, _time_ticks_20ms(inp.count_time_sec))
    header[16:24] = _ascii_bytes(_chn_date(measured_at), 8)
    header[24:28] = _ascii_bytes(f"{measured_at.hour:02d}{measured_at.minute:02d}", 4)
    struct.pack_into("<h", header, 28, 0)
    struct.pack_into("<h", header, 30, channel_count)

    trailer = bytearray(512)
    struct.pack_into("<h", trailer, 0, -102)
    struct.pack_into("<f", trailer, 4, float(res.eff_a))
    struct.pack_into("<f", trailer, 8, float(res.eff_b))
    struct.pack_into("<f", trailer, 12, 0.0)
    struct.pack_into("<f", trailer, 16, 1.0)
    struct.pack_into("<f", trailer, 20, 0.0)
    struct.pack_into("<f", trailer, 24, 0.0)
    _write_counted_text(trailer, 256, 257, 63, detector_description)
    _write_counted_text(trailer, 320, 321, 63, sample_description or build_sample_description(inp))

    return bytes(header) + struct.pack(f"<{channel_count}i", *counts) + bytes(trailer)


def build_spc_bytes(
    inp: Any,
    res: Any,
    detector_description: str = DEFAULT_DETECTOR_DESCRIPTION,
    sample_description: Optional[str] = None,
    spectrum_name: str = "GREASPY",
    measurement_datetime: Optional[dt.datetime] = None,
    detector_number: int = DEFAULT_DETECTOR_NUMBER,
    segment_number: int = DEFAULT_SEGMENT_NUMBER,
    shielding_materials: Sequence[str] = DEFAULT_SHIELDING_MATERIALS,
) -> bytes:
    """Build a minimal ORTEC real-format SPC file (FILTYP=5)."""

    counts = [float(v) for v in res.total_counts]
    _validate_float_counts(counts, ".spc")
    channel_count = len(counts)
    _require_i16_range(channel_count, "SPC channel count")

    spectrum_record_count = math.ceil(channel_count / 32)
    acq_record = 2
    sample_record = 3
    detector_record = 4
    calibration_desc_record = 5
    calibration_data_record = 6
    first_spectrum_record = 7
    total_records = first_spectrum_record + spectrum_record_count - 1
    _require_i16_range(total_records, "SPC record count")

    measured_at = _local_datetime(measurement_datetime)
    real_time = _real_time_seconds(inp, res, shielding_materials)

    header = _blank_record(0)
    _pack_i16(header, 1, 1)
    _pack_i16(header, 2, 5)
    _pack_i16(header, 3, 0)
    _pack_i16(header, 5, acq_record)
    _pack_i16(header, 6, sample_record)
    _pack_i16(header, 7, detector_record)
    _pack_i16(header, 17, calibration_desc_record)
    _pack_i16(header, 18, calibration_data_record)
    _pack_i16(header, 28, total_records)
    _pack_i16(header, 29, total_records)
    _pack_i16(header, 31, first_spectrum_record)
    _pack_i16(header, 32, spectrum_record_count)
    _pack_i16(header, 33, channel_count)
    _pack_i16(header, 34, 0)
    _pack_f32(header, 35, 0.0)
    _pack_f64(header, 37, 0.0)
    _pack_i16(header, 41, 0)
    _pack_i16(header, 42, int(detector_number))
    _pack_i16(header, 43, int(segment_number))
    _pack_i16(header, 44, 0)
    _pack_i16(header, 45, 0)
    _pack_f32(header, 46, real_time)
    _pack_f32(header, 48, float(inp.count_time_sec))
    _pack_f32(header, 63, 0.0)

    acq = _blank_record(ord(" "))
    _write_ascii(acq, 0, 16, spectrum_name)
    _write_ascii(acq, 16, 12, _spc_date(measured_at))
    _write_ascii(acq, 28, 10, measured_at.strftime("%H:%M:%S"))
    _write_ascii(acq, 38, 10, f"{round(float(inp.count_time_sec)):d}")
    _write_ascii(acq, 48, 10, f"{round(real_time):d}")

    sample = _two_line_record(sample_description or build_sample_description(inp), "")
    detector = _two_line_record(detector_description, "")
    cal_desc = _two_line_record("Energy calibration generated by GREASPY", "No efficiency calibration")

    cal_data = _blank_record(0)
    _pack_i16(cal_data, 3, 0)
    _pack_i16(cal_data, 4, channel_count)
    _pack_f32(cal_data, 11, float(res.eff_a))
    _pack_f32(cal_data, 13, float(res.eff_b))
    _pack_f32(cal_data, 15, 0.0)
    _pack_f32(cal_data, 17, 1.0)
    _pack_f32(cal_data, 19, 0.0)
    _pack_f32(cal_data, 21, 0.0)
    _pack_i16(cal_data, 35, 0)
    _pack_i16(cal_data, 38, 0)
    _pack_i16(cal_data, 39, int(detector_number))

    records = [header, acq, sample, detector, cal_desc, cal_data]
    for start in range(0, channel_count, 32):
        record = _blank_record(0)
        chunk = counts[start:start + 32]
        for idx, value in enumerate(chunk):
            struct.pack_into("<f", record, idx * 4, value)
        records.append(record)

    return b"".join(bytes(record) for record in records)


def build_n42_text(
    inp: Any,
    res: Any,
    detector_description: str = DEFAULT_DETECTOR_DESCRIPTION,
    analysis_program: str = DEFAULT_ANALYSIS_PROGRAM,
    measurement_datetime: Optional[dt.datetime] = None,
    shielding_materials: Sequence[str] = DEFAULT_SHIELDING_MATERIALS,
    document_uuid: Optional[str] = None,
) -> str:
    measured_at = _local_datetime(measurement_datetime).astimezone()
    doc_uuid = document_uuid or str(uuid.uuid4())

    ET.register_namespace("", N42_NAMESPACE)
    ET.register_namespace("xsi", XSI_NAMESPACE)
    ns = f"{{{N42_NAMESPACE}}}"
    xsi = f"{{{XSI_NAMESPACE}}}"

    root = ET.Element(
        f"{ns}RadInstrumentData",
        {
            f"{xsi}schemaLocation": f"{N42_NAMESPACE} http://physics.nist.gov/N42/2011/n42.xsd",
            "n42DocUUID": doc_uuid,
        },
    )

    instrument = ET.SubElement(root, f"{ns}RadInstrumentInformation", {"id": "RadInstrumentInformation-1"})
    ET.SubElement(instrument, f"{ns}RadInstrumentManufacturerName").text = "Idaho National Laboratory"
    ET.SubElement(instrument, f"{ns}RadInstrumentModelName").text = "GREASPY"
    ET.SubElement(instrument, f"{ns}RadInstrumentClassCode").text = "Radionuclide Identifier"
    version = ET.SubElement(instrument, f"{ns}RadInstrumentVersion")
    ET.SubElement(version, f"{ns}RadInstrumentComponentName").text = "Software"
    ET.SubElement(version, f"{ns}RadInstrumentComponentVersion").text = analysis_program

    detector = ET.SubElement(root, f"{ns}RadDetectorInformation", {"id": "RadDetectorInformation-1"})
    ET.SubElement(detector, f"{ns}RadDetectorCategoryCode").text = "Gamma"
    ET.SubElement(detector, f"{ns}RadDetectorKindCode").text = "NaI"
    ET.SubElement(detector, f"{ns}RadDetectorDescription").text = detector_description

    calibration = ET.SubElement(root, f"{ns}EnergyCalibration", {"id": "EnergyCalibration-1"})
    ET.SubElement(calibration, f"{ns}CoefficientValues").text = (
        f"{_format_n42_float(res.eff_a)} {_format_n42_float(res.eff_b)} 0"
    )

    measurement = ET.SubElement(root, f"{ns}RadMeasurement", {"id": "RadMeasurement-1"})
    ET.SubElement(measurement, f"{ns}MeasurementClassCode").text = "Foreground"
    ET.SubElement(measurement, f"{ns}StartDateTime").text = measured_at.isoformat()
    ET.SubElement(measurement, f"{ns}RealTimeDuration").text = _iso8601_duration(
        _real_time_seconds(inp, res, shielding_materials)
    )

    spectrum = ET.SubElement(
        measurement,
        f"{ns}Spectrum",
        {
            "id": "RadMeasurement-1Spectrum-1",
            "radDetectorInformationReference": "RadDetectorInformation-1",
            "energyCalibrationReference": "EnergyCalibration-1",
        },
    )
    ET.SubElement(spectrum, f"{ns}LiveTimeDuration").text = _iso8601_duration(inp.count_time_sec)
    channel_data = ET.SubElement(spectrum, f"{ns}ChannelData", {"compressionCode": "None"})
    channel_data.text = _format_multiline_numbers((_format_n42_float(v) for v in res.total_counts), 12)

    ET.indent(root, space="  ")
    xml = ET.tostring(root, encoding="unicode", short_empty_elements=False)
    return "<?xml version=\"1.0\"?>\n" + xml + "\n"


def build_sample_description(inp: Any) -> str:
    active = [(name, activity) for name, activity in inp.isotopes if name and activity > 0]
    if not active:
        return "GREASPY simulated spectrum"
    parts = [f"{name}={activity:.2E} Ci" for name, activity in active[:3]]
    if len(active) > 3:
        parts.append(f"plus {len(active) - 3} more")
    return "GREASPY " + ", ".join(parts)


def _shielding_enabled(inp: Any, shielding_materials: Sequence[str]) -> bool:
    return sum(max(0.0, float(inp.shielding_cm.get(m, 0.0))) for m in shielding_materials) > 0


def _metric(res: Any, shield_on: bool, shielded_name: str, unshielded_name: str) -> float:
    value = getattr(res, shielded_name) if shield_on else None
    if value is None:
        value = getattr(res, unshielded_name)
    return float(value)


def _real_time_seconds(inp: Any, res: Any, shielding_materials: Sequence[str]) -> float:
    return _metric(res, _shielding_enabled(inp, shielding_materials), "shielded_real_time_sec", "unshielded_real_time_sec")


def _local_datetime(value: Optional[dt.datetime]) -> dt.datetime:
    if value is None:
        return dt.datetime.now().astimezone()
    if value.tzinfo is None:
        return value.astimezone()
    return value


def _ascii_bytes(text: str, length: int, pad: bytes = b" ") -> bytes:
    raw = str(text).encode("ascii", errors="replace")[:length]
    return raw + pad * (length - len(raw))


def _write_ascii(buf: bytearray, offset: int, length: int, text: str) -> None:
    buf[offset:offset + length] = _ascii_bytes(text, length)


def _write_counted_text(buf: bytearray, length_offset: int, text_offset: int, max_len: int, text: str) -> None:
    raw = str(text).encode("ascii", errors="replace")[:max_len]
    buf[length_offset] = len(raw)
    buf[text_offset:text_offset + max_len] = raw + b" " * (max_len - len(raw))


def _blank_record(fill: int) -> bytearray:
    return bytearray([fill] * 128)


def _two_line_record(line1: str, line2: str) -> bytearray:
    record = _blank_record(ord(" "))
    _write_ascii(record, 0, 64, line1)
    _write_ascii(record, 64, 64, line2)
    return record


def _pack_i16(record: bytearray, word_number: int, value: int) -> None:
    struct.pack_into("<h", record, (word_number - 1) * 2, int(value))


def _pack_f32(record: bytearray, word_number: int, value: float) -> None:
    struct.pack_into("<f", record, (word_number - 1) * 2, float(value))


def _pack_f64(record: bytearray, word_number: int, value: float) -> None:
    struct.pack_into("<d", record, (word_number - 1) * 2, float(value))


def _integer_counts(values: Iterable[float], format_label: str) -> List[int]:
    out: List[int] = []
    for index, raw in enumerate(values):
        value = float(raw)
        if not math.isfinite(value):
            raise ValueError(f"{format_label} export cannot store non-finite count at channel {index}.")
        integer = int(round(max(0.0, value)))
        if integer > INT32_MAX:
            raise ValueError(
                f"{format_label} export cannot store channel {index} count {integer}; "
                "the format uses signed 32-bit integer channel counts."
            )
        out.append(integer)
    return out


def _validate_float_counts(values: Iterable[float], format_label: str) -> None:
    for index, value in enumerate(values):
        if not math.isfinite(float(value)):
            raise ValueError(f"{format_label} export cannot store non-finite count at channel {index}.")


def _require_i16_range(value: int, label: str) -> None:
    if not (-32768 <= int(value) <= 32767):
        raise ValueError(f"{label} must fit in a signed 16-bit integer; got {value}.")


def _time_ticks_20ms(seconds: float) -> int:
    ticks = int(round(max(0.0, float(seconds)) * 50.0))
    if ticks > INT32_MAX:
        raise ValueError("Time value is too large for a signed 32-bit 20 ms tick count.")
    return ticks


def _chn_date(value: dt.datetime) -> str:
    century_marker = "1" if value.year >= 2000 else " "
    return f"{value.day:02d}{value.strftime('%b').upper()}{value.year % 100:02d}{century_marker}"


def _spc_date(value: dt.datetime) -> str:
    century_marker = "1" if value.year >= 2000 else " "
    return f"{value.day:02d}-{value.strftime('%b').upper()}-{value.year % 100:02d}{century_marker}"


def _iso8601_duration(seconds: float) -> str:
    value = max(0.0, float(seconds))
    if abs(value - round(value)) < 1e-9:
        return f"PT{int(round(value))}S"
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return f"PT{text}S"


def _format_n42_float(value: Any) -> str:
    return f"{float(value):.6f}"


def _format_multiline_numbers(values: Iterable[str], per_line: int) -> str:
    rows: List[str] = []
    row: List[str] = []
    for value in values:
        row.append(value)
        if len(row) == per_line:
            rows.append(" ".join(row))
            row = []
    if row:
        rows.append(" ".join(row))
    return "\n        " + "\n        ".join(rows) + "\n      "
